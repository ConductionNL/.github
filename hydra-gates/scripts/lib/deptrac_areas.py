"""Write a deptrac config from the functional areas in an app's components file.

    python3 deptrac_areas.py <app> [--components FILE] [--shared NAME] [--out FILE] [--check]

Every `components:` entry of the components file (default <app>/sigrid.components.yaml) becomes a
deptrac layer with one directory collector per include pattern. An include pattern such as
`.*/lib/Db/(A|B)[.]php` is matched by the scorer against the full path; deptrac matches its
collector anywhere in the path, so the leading `.*/` is dropped and a `$` is added. Exclude
patterns are not carried over. The ruleset lets every area use the --shared area (default Kernel)
and nothing else, so each reference from one area into another is reported as a violation. When
no area carries the shared name, no area may use any other.

Without --out the config goes to stdout. With --out it is written to FILE; --check then exits 1
when FILE differs from what would be written. Run the config with deptrac.sh.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyse_dependencies as analysis  # noqa: E402

SHARED = "Kernel"

HEADER = """\
# GENERATED by hydra-gates deptrac_areas.py from {source}. Do not edit by hand.
#
# The functional areas of lib/ as deptrac layers. {rule}
# Run through hydra-gates deptrac.sh.
"""


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def render(definition, source, shared=SHARED):
    """The deptrac config for a `components:` definition; `source` names it in the header."""
    comps = definition["components"]
    names = list(dict.fromkeys(c["name"] for c in comps))
    has_shared = shared in names
    rule = (f"Every area may use {shared}; any other reference from one area into another is a violation."
            if has_shared else "No area may use another; every reference between areas is a violation.")
    out = [HEADER.format(source=source, rule=rule) + "deptrac:", "  paths:", "    - ./lib",
           "  exclude_files:", "    - '#/lib/Migration/#'", "  layers:"]
    collectors = {name: [] for name in names}
    for c in comps:
        collectors[c["name"]] += [p.pattern for p in c["include"]]
    for name in names:
        out += [f"    - name: {name}", "      collectors:"]
        for pattern in collectors[name]:
            value = pattern[3:] if pattern.startswith(".*/") else pattern
            out += ["        - type: directory", f"          value: {quote(value + '$')}"]
    out.append("  ruleset:")
    for name in names:
        out.append(f"    {name}: ~" if name == shared or not has_shared else f"    {name}:\n      - {shared}")
    return "\n".join(out) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("app", help="root of the app")
    ap.add_argument("--components", help=f"file with the `components:` block (default <app>/{analysis.COMPONENTS_FILE})")
    ap.add_argument("--shared", default=SHARED, help=f"the area every other area may use (default {SHARED})")
    ap.add_argument("--out", help="write the config here instead of to stdout")
    ap.add_argument("--check", action="store_true", help="with --out: exit 1 when the file is stale")
    args = ap.parse_args(argv)
    app = os.path.abspath(args.app)
    source = os.path.abspath(args.components) if args.components else analysis.default_components_file(app)
    definition = analysis.read_components(source)
    if definition is None:
        print(f"no `components:` block in {source}: there are no areas to write", file=sys.stderr)
        return 2
    text = render(definition, os.path.relpath(source, app), args.shared)
    if not args.out:
        if args.check:
            print("--check needs --out FILE", file=sys.stderr)
            return 2
        sys.stdout.write(text)
        return 0
    if args.check:
        current = ""
        if os.path.isfile(args.out):
            with open(args.out, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            print(f"{args.out} is stale: rerun deptrac_areas.py without --check")
            return 1
        return 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
